/* =====================================================================
   gf256.js  -  Arithmetic in the "Galois field" GF(256)
   =====================================================================

   WHY THIS FILE EXISTS
   --------------------
   QR codes protect your message with an error-correcting code called
   Reed-Solomon. Reed-Solomon does its maths on BYTES (numbers 0..255), but
   it needs a kind of arithmetic where:
       * adding, subtracting, multiplying and dividing two bytes always
         gives another byte (never a number bigger than 255), and
       * every non-zero byte has an inverse (so we can divide).
   Ordinary integer arithmetic can't do that. GF(256) can.

   HOW IT WORKS (the short version)
   --------------------------------
   * ADDITION (and subtraction) is just XOR (^). No carrying. a + a = 0.
   * MULTIPLICATION uses logarithms. We pick a special number, alpha = 2.
     Every non-zero byte is alpha raised to some power (0..254). We store
     two lookup tables:
         EXP[n] = alpha^n        LOG[x] = the n for which alpha^n = x
     Then  a * b = EXP[ LOG[a] + LOG[b] ]   (add the logs, look the result up)
   * Powers of alpha are generated by repeatedly doubling. When the number
     goes past 255 we XOR with 0x11D (binary 1 0001 1101). That is the
     QR standard's "primitive polynomial" x^8 + x^4 + x^3 + x^2 + 1, and
     doing this keeps every value inside one byte while still visiting all
     255 non-zero bytes exactly once.

   Everything is attached to one global object, window.QR, so that the
   other files can share it without needing modules (modules do not work
   when you double-click index.html from disk).
   ===================================================================== */
(function () {
  "use strict";
  const QR = (window.QR = window.QR || {});

  // EXP is twice as long (512) so that LOG[a] + LOG[b] (max 508) never needs
  // a "% 255" when multiplying. LOG[0] is undefined: log of zero doesn't exist.
  const EXP = new Array(512).fill(0);
  const LOG = new Array(256).fill(0);

  let x = 1; // x holds alpha^i as we loop
  for (let i = 0; i < 255; i++) {
    EXP[i] = x;
    LOG[x] = i;
    x <<= 1;                       // multiply by alpha (= 2)
    if (x & 0x100) x ^= 0x11d;     // stayed too big? reduce with the primitive polynomial
  }
  for (let i = 255; i < 512; i++) EXP[i] = EXP[i - 255]; // the cycle repeats

  /** a + b  (same as a - b) */
  function add(a, b) { return a ^ b; }

  /** a * b */
  function mul(a, b) {
    if (a === 0 || b === 0) return 0;        // zero times anything is zero
    return EXP[LOG[a] + LOG[b]];             // add the logarithms
  }

  /** a / b  (b must not be 0) */
  function div(a, b) {
    if (b === 0) throw new Error("GF(256): division by zero");
    if (a === 0) return 0;
    return EXP[(LOG[a] - LOG[b] + 255) % 255];
  }

  /** alpha^n for any integer n (negative allowed): handy for polynomial roots */
  function alphaPow(n) {
    return EXP[((n % 255) + 255) % 255];
  }

  /** the multiplicative inverse of a (1 / a) */
  function inv(a) { return div(1, a); }

  QR.GF = { EXP, LOG, add, mul, div, alphaPow, inv };
})();
